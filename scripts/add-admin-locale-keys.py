def deep_merge(base, override):
    """Recursively merge override into base."""
    for key, value in override.items():
        if key in base and isinstance(base[key], dict) and isinstance(value, dict):
            deep_merge(base[key], value)
        else:
            # Only add if key doesn't exist (don't overwrite existing)
            if key not in base:
                base[key] = value
    return base


def main():
    for lang, path in LOCALES.items():
        print(f'\n--- {lang.upper()} ({path}) ---')
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        new_keys = NEW_KEYS.get(lang, {})
        if not new_keys:
            print(f'  No new keys for {lang}')
            continue

        # Count keys before
        before = json.dumps(data)

        deep_merge(data, new_keys)

        # Count keys after
        after = json.dumps(data)
        added = len(after) - len(before)

        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')

        print(f'  Added ~{added} chars of new keys')

    print('\n✅ Done! All locale files updated.')


if __name__ == '__main__':
    main()
